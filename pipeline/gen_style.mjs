// Regenerate <skill>/references/style.md and norms.json from corpus.jsonl, anchored on the configured era.
// Everything here is measured. Interpretation belongs to the distill step (see distill/DISTILL.md).
import { writeFileSync, mkdirSync } from "node:fs";
import { cfg, readJsonl } from "../lib/config.mjs";

const all = readJsonl(cfg.corpus).filter((r) => !r.bot);
const late = all.filter((r) => r.createdAt >= cfg.era);
const strip = (b) => b.replace(/```[\s\S]*?```/g, " ").replace(/!\[[^\]]*\]\([^)]*\)/g, " ").replace(/<!--[\s\S]*?-->/g, " ");
const words = (b) => strip(b).trim().split(/\s+/).filter(Boolean).length;
const med = (a) => { const s = [...a].sort((x, y) => x - y); return s[Math.floor(s.length / 2)] ?? 0; };
const p90 = (a) => { const s = [...a].sort((x, y) => x - y); return s[Math.floor(s.length * 0.9)] ?? 0; };
const pct = (rs, re) => rs.length ? Math.round((rs.filter((r) => re.test(strip(r.body))).length / rs.length) * 100) : 0;
const EMOJI = /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/u;
const BOT = /^\s*(\/[a-z-]+test[a-z-]*|\/retest|@dependabot|@renovate)/i;
const PREFIX = /^\s*(suggestion|question|bug|nit|typo|chore|issue|blocker|praise|thought)\b/i;

const g = {
  review: late.filter((r) => r.kind === "review" && !r.ownThread),
  comment: late.filter((r) => r.kind === "comment" && !r.ownThread),
  ownComment: late.filter((r) => r.kind === "comment" && r.ownThread),
  review_comment: late.filter((r) => r.kind === "review_comment" && !r.ownThread),
  pr: late.filter((r) => r.kind === "pr"),
  issue: late.filter((r) => r.kind === "issue"),
};
const row = (name, rs) => `| ${name} | ${rs.length} | ${med(rs.map((r) => words(r.body)))} | ${p90(rs.map((r) => words(r.body)))} | ${pct(rs, /!/)}% | ${pct(rs, /\?/)}% | ${pct(rs, EMOJI)}% | ${pct(rs, /`[^`]+`/)}% | ${pct(rs, /https?:\/\//)}% |`;
const tally = (rs, key) => Object.entries(rs.reduce((m, r) => { const k = key(r); if (k) m[k] = (m[k] || 0) + 1; return m; }, {})).sort((a, b) => b[1] - a[1]);
const show = (pairs, n = 8, q = '"') => pairs.slice(0, n).map(([k, c]) => `${q}${k}${q} (${c})`).join(", ");
const reviewStates = tally(g.review, (r) => r.reviewState);
const others = [...g.review, ...g.comment].filter((r) => !BOT.test(r.body));
const openers = tally(others, (r) => strip(r.body).trim().split(/\s+/).slice(0, 2).join(" ").toLowerCase().replace(/[^a-z@' ]/g, "").trim());
const closers = tally(others, (r) => { const ls = strip(r.body).trim().split("\n").filter((l) => l.trim()); const c = (ls[ls.length - 1] || "").trim().toLowerCase(); return c.split(/\s+/).length <= 4 ? c : null; });
const emoji = tally(others, (r) => null).concat(Object.entries(others.reduce((m, r) => { for (const e of strip(r.body).match(new RegExp(EMOJI.source, "gu")) || []) m[e] = (m[e] || 0) + 1; return m; }, {})).sort((a, b) => b[1] - a[1]));
const hedges = ["i think", "i'd like to", "not sure", "perhaps", "might", "potentially", "imho", "wdyt"].map((h) => [h, late.filter((r) => strip(r.body).toLowerCase().includes(h)).length]);
const prefixes = tally(g.review_comment, (r) => (strip(r.body).match(PREFIX) || [])[1]?.toLowerCase());
const prefixByYear = tally(g.review_comment, (r) => r.createdAt.slice(0, 4)).sort().map(([y, n]) => `${y}: ${Math.round((g.review_comment.filter((r) => r.createdAt.startsWith(y) && PREFIX.test(strip(r.body))).length / n) * 100)}% of ${n}`);
const drift = Object.entries(all.filter((r) => r.kind === "comment" && !r.ownThread).reduce((m, r) => ((m[r.createdAt.slice(0, 4)] ??= []).push(r), m), {})).sort()
  .map(([y, rs]) => `| ${y} | ${rs.length} | ${med(rs.map((r) => words(r.body)))} | ${pct(rs, EMOJI)}% | ${pct(rs, /!/)}% |`).join("\n");
const rates = {
  commentListRate: pct(g.comment, /^\s*[-*] /m), commentHeaderRate: pct(g.comment, /^#+ /m), commentBoldLeadRate: pct(g.comment, /^\s*[-*] \*\*/m),
  reviewCommentPrefixRate: pct(g.review_comment, PREFIX), reviewCommentSuggestionBlockRate: g.review_comment.length ? Math.round((g.review_comment.filter((r) => /```suggestion/.test(r.body)).length / g.review_comment.length) * 100) : 0,
  gifRate: late.length ? Math.round((late.filter((r) => /giphy\.com|tenor\.com/i.test(r.body)).length / late.length) * 1000) / 10 : 0,
  // most recent year with enough inline comments: habits shift faster than the era average shows
  reviewCommentPrefixRateLatest: (() => { const ys = tally(g.review_comment, (r) => r.createdAt.slice(0, 4)).filter(([, n]) => n >= 30).map(([y]) => y).sort(); const y = ys[ys.length - 1]; return y ? pct(g.review_comment.filter((r) => r.createdAt.startsWith(y)), PREFIX) : 0; })(),
  changesRequestedRate: g.review.length ? Math.round(((reviewStates.find(([k]) => k === "CHANGES_REQUESTED")?.[1] ?? 0) / g.review.length) * 100) : 0,
};
const era = cfg.era.slice(0, 4);
const md = `# Style — measured on ${era}–${cfg.window.to.slice(0, 4)} (${late.length} texts; whole window is ${all.length})

Generated by \`node pipeline/gen_style.mjs\` from @${cfg.login}'s corpus. Do not hand-edit numbers; interpretation lives in
\`voice-notes.md\`, \`anti-patterns.md\` and the playbooks.

## Length and surface, by genre (texts in other people's threads unless noted)

| Genre | n | median words | p90 | has ! | has ? | has emoji | inline code | has link |
|---|---|---|---|---|---|---|---|---|
${row("Review summary", g.review)}
${row("Comment (others' thread)", g.comment)}
${row("Comment (own thread)", g.ownComment)}
${row("Inline review comment", g.review_comment)}
${row("PR description (own)", g.pr)}
${row("Issue (own)", g.issue)}

The lint uses the median as the target and p90 as the ceiling for each genre.

## Review verdicts (${g.review.length} reviews on others' PRs)

${reviewStates.map(([k, n]) => `- ${k}: ${n} (${Math.round((n / g.review.length) * 100)}%)`).join("\n")}

## Rituals (fixed phrases — these are the voice, use them as-is)

- Openers: ${show(openers)}
- Closers: ${show(closers)}
- Emoji actually used: ${show(emoji.filter(([k]) => k), 8, "")}
- Hedges (texts containing): ${hedges.map(([h, n]) => `"${h}" ${n}`).join(" · ")}

## Inline review comments

- Opens with a conventional-comments prefix (\`suggestion:\`, \`question:\`, \`nit:\` …): ${rates.reviewCommentPrefixRate}% overall — by year: ${prefixByYear.join(", ")}
- Prefixes used: ${show(prefixes, 8, "`")}
- Contains a \`\`\`suggestion block: ${rates.reviewCommentSuggestionBlockRate}%

## Structure (comments in others' threads)

- Markdown headers: ${rates.commentHeaderRate}% · bullet lists: ${rates.commentListRate}% · bold-lead bullets: ${rates.commentBoldLeadRate}%
- Gif or image embeds in the era: ${rates.gifRate}% of texts

## Drift over the whole window (comments in others' threads)

| Year | n | median words | has emoji | has ! |
|---|---|---|---|---|
${drift}
`;
mkdirSync(cfg.skill + "/references", { recursive: true });
writeFileSync(cfg.skill + "/references/style.md", md);
const norms = {
  login: cfg.login, name: cfg.name, pronoun: cfg.pronoun, disclosure: cfg.disclosure, era: cfg.era, generated: new Date().toISOString().slice(0, 10),
  genres: Object.fromEntries(Object.entries({ review: g.review, comment: g.comment, review_comment: g.review_comment, pr: g.pr, issue: g.issue }).map(([k, rs]) => [k, { n: rs.length, median: med(rs.map((r) => words(r.body))), p90: p90(rs.map((r) => words(r.body))) }])),
  rates, closers: closers.slice(0, 12).map(([k]) => k),
};
writeFileSync(cfg.skill + "/references/norms.json", JSON.stringify(norms, null, 2) + "\n");
console.log(md.split("\n").slice(0, 16).join("\n"));
console.log("norms:", JSON.stringify(norms.genres), JSON.stringify(rates));
