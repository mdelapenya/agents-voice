#!/usr/bin/env python3
"""Mechanical checks on a draft before posting in the subject's name. Call through `scripts/voice lint …`.

  voice lint draft.md --genre comment|review|review_comment|pr|issue
Exit 1 if any ERROR. Warnings are advisory. Norms come from ../references/norms.json (generated by gen_style).
"""
import argparse, json, os, re, sqlite3, sys

HERE = os.path.dirname(os.path.abspath(__file__))
TELLS = [r"\bgreat question\b", r"\bi hope this helps\b", r"\bhappy to help\b", r"\bas an ai\b", r"\bcertainly!", r"\babsolutely!",
         r"\bthis (pr|pull request) introduces\b", r"\bcomprehensive\b", r"\brobust\b", r"\bseamless(ly)?\b", r"\bleverag(e|ing)\b",
         r"\bin summary\b", r"\bto summarize\b", r"\boverall,", r"\bit'?s worth noting\b", r"\bplease note that\b", r"\bfeel free to reach out\b",
         r"\bi appreciate your (patience|understanding)\b", r"\bthank you for (bringing|raising) this\b", r"\bkey (changes|points|takeaways)\b"]
DEFAULT_CLOSERS = [r"thanks!?$", r"cheers!?$", r"wdyt\??$", r"🙏$", r"thank you!?$"]
PREFIX = re.compile(r"\s*(suggestion|question|bug|nit|typo|chore|issue|blocker|praise|thought)\b", re.I)
FORMULA_MIN = 3  # n-grams found in >= this many corpus texts are the subject's formulas, not copies of one exemplar
GENRES = ("review", "comment", "review_comment", "pr", "issue")

def load_norms(path):
    path = path or os.path.join(HERE, "..", "references", "norms.json")
    if not os.path.exists(path): sys.exit(f"norms.json not found at {path}; run `node pipeline/gen_style.mjs`")
    return json.load(open(path, encoding="utf-8"))

def footer_re(template):
    # "🤖 Written assisted by my {harness}" -> anchored regex; harness is a capitalised word or phrase
    esc = re.escape(template).replace(re.escape("{harness}"), r"(Claude|Codex|Cursor|Gemini|Copilot|OpenCode|Grok|Antigravity|[A-Z][A-Za-z0-9 .-]+)")
    return re.compile("^" + esc + "$")

def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("draft"); p.add_argument("--genre", required=True, choices=GENRES); p.add_argument("--db", default=None); p.add_argument("--norms", default=None)
    a = p.parse_args()
    N = load_norms(a.norms); who = N.get("name") or N.get("login") or "the subject"; rates = N.get("rates", {})
    g = N["genres"].get(a.genre) or {"median": 30, "p90": 120}
    med, ceil = g["median"], max(g["p90"], g["median"] * 2)
    FOOTER = footer_re(N.get("disclosure", "🤖 Written assisted by my {harness}"))
    closers_re = DEFAULT_CLOSERS + [re.escape(c) + "$" for c in N.get("closers", [])]

    text = open(a.draft, encoding="utf-8").read().strip()
    lines = [l for l in text.split("\n") if l.strip()]
    errors, warns = [], []
    if not lines or not FOOTER.match(lines[-1].strip()):
        errors.append(f"missing or malformed disclosure footer; last line must be exactly `{N.get('disclosure')}` with the harness name filled in")
    body = "\n".join(lines[:-1]) if lines and FOOTER.match(lines[-1].strip()) else text
    prose = re.sub(r"```[\s\S]*?```", " ", body)
    words = len(prose.split())
    if words > ceil: errors.append(f"{words} words; {a.genre} ceiling is ~{ceil} ({who}'s median is {med}). Cut it.")
    elif words > med * 2: warns.append(f"{words} words; {who}'s median for {a.genre} is {med}.")
    for t in TELLS:
        if re.search(t, prose, re.I): errors.append(f"LLM tell: /{t}/")
    if a.genre in ("comment", "review", "review_comment"):
        if re.search(r"^#+ ", prose, re.M) and rates.get("commentHeaderRate", 0) < 5: errors.append(f"markdown headers in a comment; {who} uses them in {rates.get('commentHeaderRate', 0)}% of comments")
        bullets = len(re.findall(r"^\s*[-*] ", prose, re.M))
        if bullets > 4 and rates.get("commentListRate", 0) < 10: warns.append(f"{bullets} bullet points; {who} lists in {rates.get('commentListRate', 0)}% of comments")
        if re.search(r"^\s*[-*] .*\*\*.*\*\*", prose, re.M) and rates.get("commentBoldLeadRate", 0) < 5: errors.append("bold-lead bullet list — pure LLM register")
    prefix_rate = max(rates.get("reviewCommentPrefixRate", 0), rates.get("reviewCommentPrefixRateLatest", 0))
    if a.genre == "review_comment" and prefix_rate >= 30 and not PREFIX.match(prose) and not prose.lstrip().startswith("```suggestion"):
        warns.append(f"no conventional-comment prefix (suggestion:/question:/bug:/nit:); {who} lately opens {prefix_rate}% of inline comments with one")
    closers = sum(1 for l in lines[:-1] if any(re.search(c, l.strip(), re.I) for c in closers_re))
    if closers > 1: warns.append(f"{closers} closing lines; use one")
    if prose.count("!") > 3: warns.append(f"{prose.count('!')} exclamation marks; one, usually at the end")
    if len(re.findall(r"[\U0001F300-\U0001FAFF]", prose)) > 2: warns.append("more than two emoji in body")
    if re.search(r"!\[[^\]]*\]\(", prose) or re.search(r"giphy\.com|tenor\.com", prose, re.I):
        errors.append("image/gif embed — agent-written text never posts gifs or images")
    # verbatim overlap with the corpus (>= 5 consecutive words inside one sentence)
    db = a.db or os.environ.get("VOICE_DB") or next((p for p in (os.path.join(HERE, "voice.sqlite"), os.path.join(HERE, "..", "voice.sqlite"), os.path.join(HERE, "..", "..", "voice.sqlite")) if os.path.exists(p)), None)
    if db and os.path.exists(db):
        con = sqlite3.connect(f"file:{db}?mode=ro", uri=True); seen = set(); grams = []
        for sentence in re.split(r"[.!?\n]+", prose.lower()):
            toks = re.findall(r"[A-Za-z0-9']+", sentence)
            grams += [" ".join(toks[i:i + 5]) for i in range(0, max(0, len(toks) - 4))]
        for gram in grams:
            if gram in seen or len(gram) < 24: continue
            seen.add(gram)
            hits = con.execute("SELECT rec.id FROM fts JOIN rec ON rec.rowid = fts.rowid WHERE fts MATCH ? LIMIT ?", ('"' + gram + '"', FORMULA_MIN)).fetchall()
            if 0 < len(hits) < FORMULA_MIN: errors.append(f"verbatim 5-gram copied from one exemplar: “{gram}” ({hits[0][0]})")
    else:
        warns.append("voice.sqlite not found; skipped verbatim-copy check")
    for e in errors: print("ERROR", e)
    for w in warns: print("WARN ", w)
    if not errors and not warns: print("ok:", words, "words")
    sys.exit(1 if errors else 0)

if __name__ == "__main__": main()
